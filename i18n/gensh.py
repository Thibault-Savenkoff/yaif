#!/usr/bin/env python3
"""i18n/gensh.py          writes the i18n block of install.sh (between its markers) and i18n/sh/lib.sh
                         from i18n/sh/<lang>.tsv
   i18n/gensh.py --check also checks the sources: every message of install.sh / build.sh is in fr.tsv, no
                         stale key, same %1..%6 in every translation, the block is current. Exit 1 on a problem.
A .tsv line is  English<TAB>translation. The English text is the key and the fallback. Messages are written in
the shell as  step|info|ok|warn|die|ask|argerr|t "English text %1" value...  (see t() in the block)."""
import os, re, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# columns: the CLI's languages (i18n/gen.py), Arabic excluded there too
LANGS = re.search(r'^LANGS = "([^"]+)"', open(root + '/i18n/gen.py', encoding='utf-8').read(), re.M).group(1).split()
SRC = ['install.sh', 'build.sh']
BEGIN, END = '# >>> i18n (generated by i18n/gensh.py from i18n/sh/*.tsv; do not edit) >>>', '# <<< i18n <<<'

def load(lang):
    d, p = {}, f'{root}/i18n/sh/{lang}.tsv'
    if os.path.exists(p):
        for n, line in enumerate(open(p, encoding='utf-8'), 1):
            line = line.rstrip('\n')
            if not line or line.startswith('#'): continue
            if '\t' not in line: sys.exit(f'{p}:{n}: no tab')
            k, v = line.split('\t', 1)
            d[k] = v
    return d

def unesc(s): return re.sub(r'\\(["\\$`])', r'\1', s)

def used():
    keys = set()
    for f in SRC:
        s = open(f'{root}/{f}', encoding='utf-8').read()
        s = s[:s.find(BEGIN)] + s[s.find(END):] if BEGIN in s else s
        for m in re.finditer(r'(?<![\w$.-])(?:step|info|ok|warn|die|ask|argerr|t)[ ]+"((?:[^"\\]|\\.)*)"', s):
            keys.add(unesc(m.group(1)))
        m = re.search(r'usage\(\) \{.*?<<\'EOF\'\n(.*?)\nEOF', s, re.S)
        if m:
            for l in m.group(1).split('\n'):
                if l.strip(): keys.add(l)
    # no letters, a bare variable, or the command lines of the usage text: nothing to translate
    return {k for k in keys if re.search(r'[A-Za-z]', re.sub(r'%[1-6]', '', k)) and not k.startswith('$') and not re.match(r'\s+install\.sh', k)}

def block(tr):
    cols = {l: i + 2 for i, l in enumerate(LANGS)}
    keys = sorted(used(), key=lambda k: k.encode())
    L = [BEGIN, 'i18n_col=0',
         "i18n_awk='BEGIN { FS = \"\\t\"; k = ENVIRON[\"I18N_K\"]; c = ENVIRON[\"I18N_C\"] + 0; out = k }",
         'c > 0 && $1 == k && $c != "" { out = $c; exit }',
         'END { r = ""; while ((p = match(out, /%[1-6]/)) > 0) { r = r substr(out, 1, p - 1) ENVIRON["I18N_" substr(out, p + 1, 1)]; out = substr(out, p + 2) } printf "%s", r out }\'',
         '',
         '# i18n_pick: YAIF_LANG, else LC_ALL / LC_MESSAGES / LANG (UTF-8 only: the text is UTF-8); C, POSIX, en: English',
         'i18n_pick() {',
         '  local l=${YAIF_LANG:-}',
         '  if [ -z "$l" ]; then',
         '    l=${LC_ALL:-${LC_MESSAGES:-${LANG:-}}}',
         '    case $l in *[Uu][Tt][Ff]-8* | *[Uu][Tt][Ff]8*) ;; *) return 0 ;; esac',
         '  fi',
         '  l=${l%%.*}; l=${l%%@*}',
         '  case $l in']
    def pat(l):
        return {'zh_Hans': None, 'zh_Hant': None, 'pt_BR': 'pt_BR', 'pt': 'pt|pt_*'}.get(l, f'{l}|{l}_*')
    for l in LANGS:
        if l == 'zh_Hant': L.append(f'    zh_TW* | zh_HK* | zh_MO* | zh_Hant*) i18n_col={cols[l]} ;;')
        elif l == 'zh_Hans': L.append(f'    zh*) i18n_col={cols[l]} ;;')
    for l in LANGS:
        if l in ('zh_Hans', 'zh_Hant'): continue
        L.append(f'    {pat(l)}) i18n_col={cols[l]} ;;')
    # zh_Hant must be tried before zh*: move the zh lines first
    zh = [x for x in L if x.lstrip().startswith('zh')]
    L = [x for x in L if x not in zh]
    at = L.index('  case $l in') + 1
    L[at:at] = [x for x in zh if x.lstrip().startswith('zh_TW')] + [x for x in zh if x.lstrip().startswith('zh*')]
    L += ['  esac', '}', '',
          '# t "English text with %1..%6" [values...]: that text in the user\'s language (English when not translated)',
          't() {',
          '  if [ "$i18n_col" -gt 0 ]; then',
          '    i18n_data | I18N_K=$1 I18N_C=$i18n_col I18N_1=${2-} I18N_2=${3-} I18N_3=${4-} I18N_4=${5-} I18N_5=${6-} I18N_6=${7-} awk "$i18n_awk"',
          '  else',
          '    I18N_K=$1 I18N_C=0 I18N_1=${2-} I18N_2=${3-} I18N_3=${4-} I18N_4=${5-} I18N_5=${6-} I18N_6=${7-} awk "$i18n_awk" </dev/null',
          '  fi',
          '}',
          '',
          '# English<TAB>one column per language: ' + ' '.join(LANGS),
          'i18n_data() {', "  cat <<'I18N_EOF'"]
    for k in keys:
        L.append('\t'.join([k] + [tr[l].get(k, '') for l in LANGS]))
    L += ['I18N_EOF', '}', 'i18n_pick', END]
    return '\n'.join(L)


PS = f'{root}/install.ps1'
UNSPLIT = "@'\n$dir = $PSScriptRoot"
def ps_keys(text):
    text = re.sub(r'# >>> i18n ps:.*?# <<< i18n ps:\w+ <<<', '', text, flags=re.S)
    ks = set()
    for m in re.finditer(r"(?<![\w$.-])T '((?:[^']|'')*)'", text):
        ks.add(m.group(1).replace("''", "'"))
    return ks
def ps_parts():
    s = open(PS, encoding='utf-8').read()
    out = {}
    for name, pat in (('main', 'main'), ('uninstall', 'uninstall')):
        b = f'# >>> i18n ps:{name} '
        out[name] = (b, f'# <<< i18n ps:{name} <<<')
    return s, out
def ps_block(name, keys, tr):
    cols = {l: i + 2 for i, l in enumerate(LANGS)}
    q = lambda x: x.replace("'", "''")
    rows = '\n'.join('\t'.join([k] + [tr[l].get(k, '') for l in LANGS]) for k in sorted(keys, key=lambda k: k.encode()))
    sw = ["    '^zh_(TW|HK|MO|Hant)' { %d; break }" % cols['zh_Hant'], "    '^zh' { %d; break }" % cols['zh_Hans'], "    '^pt_BR' { %d; break }" % cols['pt_BR']]
    for l in LANGS:
        if l not in ('zh_Hans', 'zh_Hant', 'pt_BR'): sw.append("    '^%s(_|$)' { %d; break }" % (l, cols[l]))
    L = [f'# >>> i18n ps:{name} (generated by i18n/gensh.py from i18n/sh/*.tsv; do not edit) >>>',
         "$i18n_l = if ($env:YAIF_LANG) { $env:YAIF_LANG } else { (Get-UICulture).Name }",
         "$i18n_c = switch -Regex ($i18n_l -replace '-', '_') {"] + sw + ["    default { 0 }", "}",
         "if ($i18n_c) { try { [Console]::OutputEncoding = [Text.Encoding]::UTF8 } catch {} }",
         "function T {   # T 'English text %1' value...: that text in the user's language (English when not translated)",
         "    $r = $args[0]",
         "    if ($i18n_c) { foreach ($ln in $i18n -split \"\\r?\\n\") { $f = $ln.Split(\"`t\"); if ($f[0] -eq $args[0] -and $f[$i18n_c - 1]) { $r = $f[$i18n_c - 1]; break } } }",
         "    for ($j = 1; $j -lt $args.Count; $j++) { $r = $r.Replace(\"%$j\", [string]$args[$j]) }",
         "    $r",
         "}",
         "# English<TAB>one column per language: " + ' '.join(LANGS),
         "$i18n = '" + q(rows) + "'",
         f'# <<< i18n ps:{name} <<<']
    return '\n'.join(L)

tr = {l: load(l) for l in LANGS}
blk = block(tr)
check = '--check' in sys.argv
bad = 0
ins = f'{root}/install.sh'; s = open(ins, encoding='utf-8').read()
if BEGIN in s:
    new = s[:s.index(BEGIN)] + blk + s[s.index(END) + len(END):]
    if check:
        if new != s: print('install.sh: i18n block out of date (run i18n/gensh.py)'); bad += 1
    else: open(ins, 'w', encoding='utf-8').write(new)
else: print('install.sh: no i18n markers'); bad += 1
lib = f'{root}/i18n/sh/lib.sh'
text = '# Generated by i18n/gensh.py (sourced by build.sh); the same block is embedded in install.sh.\n' + blk + '\n'
if check:
    if not os.path.exists(lib) or open(lib, encoding='utf-8').read() != text: print('i18n/sh/lib.sh out of date'); bad += 1
else: open(lib, 'w', encoding='utf-8').write(text)

s, marks = ps_parts()
cut = s.find(UNSPLIT)
if cut < 0: print('install.ps1: uninstaller start not found'); bad += 1; cut = len(s)
psk = {'main': ps_keys(s[:cut]), 'uninstall': ps_keys(s[cut:])}
new = s
for name in ('main', 'uninstall'):
    b, e = marks[name]
    i = new.find(b)
    if i < 0: print(f'install.ps1: no ps:{name} markers'); bad += 1; continue
    j = new.index(e, i) + len(e)
    new = new[:i] + ps_block(name, psk[name], tr) + new[j:]
if check:
    if new != s: print('install.ps1: i18n blocks out of date (run i18n/gensh.py)'); bad += 1
else: open(PS, 'w', encoding='utf-8', newline='').write(new)
if check:
    u = used() | psk['main'] | psk['uninstall']; ref = set(tr['fr'])
    for k in sorted(u - ref): print('no French text for:', repr(k)); bad += 1
    for k in sorted(ref - u): print('unused key:', repr(k)); bad += 1
    for l in LANGS:
        for k, v in tr[l].items():
            if k not in ref: print(l, 'stale key', repr(k)); bad += 1
            elif sorted(re.findall(r'%[1-6]', k)) != sorted(re.findall(r'%[1-6]', v)): print(l, 'placeholders differ:', repr(k)); bad += 1
    print('i18n sh: ' + ('FAIL' if bad else 'ok') + f', {len(u)} messages')
    sys.exit(1 if bad else 0)
