#!/usr/bin/env python3
"""i18n/gen.py          writes yaif_msgs.h from i18n/<lang>.tsv
   i18n/gen.py --check  also checks the sources: every Yaif_i18n.t*"text" key is in fr.tsv, no stale key,
                        the same %1..%4 in every translation, yaif_msgs.h is current. Exit 1 on any problem.
A .tsv line is  English<TAB>translation  (\\n \\t \\\\ escaped). The English text is the key and the fallback."""
import glob, os, re, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# columns of the table: the languages of win/lang.nsh minus English
# ar is written (i18n/ar.tsv) but NOT listed: GNOME Terminal (VTE) shows it with unjoined letters and
# scrambled word order (seen 2026-11-27), so Arabic falls back to English. Add "ar" back when terminals shape it.
LANGS = "fr es de it pt_BR pt nl ru pl tr ja ko zh_Hans zh_Hant hi id vi uk".split()

def unesc(s):
    return re.sub(r'\\(.)', lambda m: {'n': '\n', 't': '\t', '\\': '\\', '"': '"'}.get(m.group(1), m.group(0)), s)

def esc(s):
    return s.replace('\\', '\\\\').replace('\n', '\\n').replace('\t', '\\t')

def load(lang):
    d, p = {}, os.path.join(root, 'i18n', lang + '.tsv')
    if os.path.exists(p):
        for n, line in enumerate(open(p, encoding='utf-8'), 1):
            line = line.rstrip('\n')
            if not line or line.startswith('#'): continue
            if '\t' not in line: sys.exit(f'{p}:{n}: no tab')
            k, v = line.split('\t', 1)
            d[unesc(k)] = unesc(v)
    return d

def c_str(s):
    out = ''
    for b in s.encode('utf-8'):
        if b == 0x22: out += '\\"'
        elif b == 0x5c: out += '\\\\'
        elif b == 0x0a: out += '\\n'
        elif b == 0x09: out += '\\t'
        elif 32 <= b < 127 and b != 0x3f: out += chr(b)   # ? : no trigraphs
        else: out += '\\%03o' % b
    return '"' + out + '"'

tr = {l: load(l) for l in LANGS}
keys = sorted({k for d in tr.values() for k in d}, key=lambda k: k.encode())
hdr = ['/* generated by i18n/gen.py from i18n/*.tsv: do not edit */',
       f'#define YI_NLANG {len(LANGS)}', f'#define YI_NKEYS {len(keys)}',
       'static const char *const yi_names[YI_NLANG] = {' + ', '.join(c_str(l) for l in LANGS) + '};',
       'static const struct { const char *en; const char *tr[YI_NLANG]; } yi_tab[YI_NKEYS] = {']
for k in keys:
    hdr.append('  {' + c_str(k) + ', {' + ', '.join(c_str(tr[l][k]) if k in tr[l] else '0' for l in LANGS) + '}},')
hdr.append('};')
text = '\n'.join(hdr) + '\n'
out = os.path.join(root, 'yaif_msgs.h')

if '--check' not in sys.argv:
    open(out, 'w', encoding='utf-8').write(text)
    print(f'{out}: {len(keys)} messages, {sum(1 for l in LANGS if tr[l])} languages')
    sys.exit(0)

bad = 0
used = set()
for f in glob.glob(os.path.join(root, '*.li')):
    src = open(f, encoding='utf-8').read()
    for m in re.finditer(r'(?:Yaif_i18n\.t[1-4]?\s*\(?\s*|^\s*say\s+|yi_fmt\()"((?:[^"\\]|\\.)*)"', src, re.M):
        used.add(unesc(m.group(1)))
for k in sorted(used - set(keys)): print('no translation file has:', repr(k)); bad += 1
for k in sorted(set(keys) - used): print('unused key:', repr(k)); bad += 1
for l in LANGS:
    for k, v in tr[l].items():
        if sorted(re.findall(r'%[1-4]', k)) != sorted(re.findall(r'%[1-4]', v)):
            print(f'{l}: placeholders differ in', repr(k)); bad += 1
if not os.path.exists(out) or open(out, encoding='utf-8').read() != text:
    print('yaif_msgs.h is not current: run python3 i18n/gen.py'); bad += 1
print('i18n: ' + ('FAIL' if bad else 'ok') + f', {len(keys)} messages')
sys.exit(1 if bad else 0)
